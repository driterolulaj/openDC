/**
 * `npm run openapi` writes packages/api/openapi.json and the CLI's operation table
 * (packages/cli/src/generated/operations.ts) from the route table; `--check` fails if either is stale.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { openDb } from '@opendc/shared/db';
import { PlatformError } from '@opendc/shared';
import { apiMigrations } from '../db.ts';
import { buildApi } from '../server.ts';
import { buildOpenApi } from '../http/openapi.ts';

const out = resolve(import.meta.dirname, '../../openapi.json');
const api = await buildApi({
  db: openDb(':memory:', apiMigrations),
  directory: { authenticate: () => Promise.reject(new PlatformError('internal', { requestId: 'openapi' })) },
  agent: null,
  nodeId: 'openapi',
  csrfKey: Buffer.alloc(32),
  idleMinutes: 30,
  absoluteHours: 12,
  webDir: null,
  validateResponses: false,
});
const doc = JSON.stringify(buildOpenApi(api.routes.routes), null, 2) + '\n';

// the CLI's view of the API: every /api/v1 operation, its path/query parameters and whether it has a body
const shapeKeys = (schema: unknown): string[] => {
  const shape = (schema as { shape?: Record<string, unknown> } | undefined)?.shape;
  return shape ? Object.keys(shape) : [];
};
const ops = api.routes.routes
  .filter((r) => r.url.startsWith('/api/v1/'))
  .map((r) => ({
    operationId: r.operationId,
    method: r.method,
    path: r.url,
    tag: r.tags[0] ?? '',
    summary: r.summary,
    pathParams: shapeKeys(r.params),
    queryParams: shapeKeys(r.query),
    body: r.body !== undefined,
    stream: r.stream === true,
    auth: typeof r.auth === 'object' ? r.auth.permission : r.auth,
  }))
  .sort((a, b) => a.operationId.localeCompare(b.operationId));
const cliOut = resolve(import.meta.dirname, '../../../cli/src/generated/operations.ts');
const cliDoc =
  '// Generated by `npm run openapi` from the API route table. DO NOT EDIT.\n// SPDX-License-Identifier: AGPL-3.0-only\n\n' +
  `export const operations = ${JSON.stringify(ops, null, 2)} as const;\n\nexport type Operation = (typeof operations)[number];\n`;
await api.app.close();

if (process.argv.includes('--check')) {
  let stale = false;
  for (const [file, content] of [
    [out, doc],
    [cliOut, cliDoc],
  ] as const) {
    if (!existsSync(file) || readFileSync(file, 'utf8') !== content) {
      console.error(`${file} is stale; run npm run openapi and review the API diff.`);
      stale = true;
    }
  }
  if (stale) process.exit(1);
  console.log('openapi.json and the CLI operation table are up to date');
} else {
  writeFileSync(out, doc);
  mkdirSync(dirname(cliOut), { recursive: true });
  writeFileSync(cliOut, cliDoc);
  console.log(`wrote ${out} and ${cliOut}`);
}
