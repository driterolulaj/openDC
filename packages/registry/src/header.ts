/** The generated-file header every managed file starts with (ADR-0005 §3), per comment style. */

export type CommentStyle = 'hash' | 'semicolon' | 'slash' | 'xml' | 'json-field' | 'none';

export const JSON_HEADER_FIELD = '_generated';

export function headerText(module: string, fileId: string): string {
  return `Generated by OpenDC (module ${module}, template ${fileId}). DO NOT EDIT - changes will be overwritten. See: opendc registry explain ${fileId}`;
}

/** Returns the file content with the header applied. `json-field` content must be a JSON object. */
export function withHeader(style: CommentStyle, module: string, fileId: string, body: string): string {
  const text = headerText(module, fileId);
  switch (style) {
    case 'hash':
      return `# ${text}\n${body}`;
    case 'semicolon':
      return `; ${text}\n${body}`;
    case 'slash':
      return `// ${text}\n${body}`;
    case 'xml': {
      // Keep an XML declaration first if the body has one.
      const m = /^<\?xml[^>]*\?>\n?/.exec(body);
      return m ? `${m[0].endsWith('\n') ? m[0] : m[0] + '\n'}<!-- ${text} -->\n${body.slice(m[0].length)}` : `<!-- ${text} -->\n${body}`;
    }
    case 'json-field': {
      const parsed: unknown = body.trim() === '' ? {} : JSON.parse(body);
      if (!parsed || typeof parsed !== 'object' || Array.isArray(parsed)) throw new TypeError(`${fileId}: json-field files must render a JSON object`);
      const { [JSON_HEADER_FIELD]: _old, ...rest } = parsed as Record<string, unknown>;
      return JSON.stringify({ [JSON_HEADER_FIELD]: text, ...rest }, null, 2) + '\n';
    }
    case 'none':
      return body;
  }
}
