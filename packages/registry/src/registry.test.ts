const sha = (s: string): string => createHash('sha256').update(s).digest('hex');

const keys: RegistryKeyDefinition[] = [
  { name: 'demo.message', schema: z.string().max(10), default: 'hi', description: 'demo:k', policySettable: true },
  {
    name: 'demo.port',
    schema: z.number().int().min(1).max(65535),
    default: 80,
    description: 'demo:k',
    policySettable: false,
  },
  { name: 'other.flag', schema: z.boolean(), default: false, description: 'demo:k', policySettable: true },
];

const isCode = (code: string) => (e: unknown) => e instanceof PlatformError && e.code === code;

test('layer precedence and explain', () => {
  const r = new Registry(keys, {
    'domain-policy': { 'demo.message': 'policy', 'demo.port': 8080 },
    local: { 'demo.message': 'local' },
    forced: { 'other.flag': true },
  });
  assert.equal(r.get('demo.message'), 'local');
  assert.equal(r.get('other.flag'), true);
  // demo.port is not policySettable: the policy value is ignored
  assert.equal(r.get('demo.port'), 80);
  const e = r.explain('demo.message');
  assert.equal(e.layer, 'local');
  assert.deepEqual(
    e.defined.map((d) => d.layer),
    ['default', 'domain-policy', 'local'],
  );
  assert.equal(r.explain('demo.port').defined.find((d) => d.layer === 'domain-policy')?.valid, false);
  assert.deepEqual(r.keys(), ['demo.message', 'demo.port', 'other.flag']);
  assert.equal(r.withLayer('forced', { 'demo.message': 'forced' }).get('demo.message'), 'forced');
  assert.deepEqual(r.layer('local'), { 'demo.message': 'local' });
});

test('invalid layer values never win and are reported', () => {
  const r = new Registry(keys, {
    local: { 'demo.message': 'far too long a message', 'demo.port': 443, 'gone.key': 1 },
    'domain-policy': { 'demo.port': 1 },
  });
  assert.equal(r.get('demo.message'), 'hi');
  assert.equal(r.get('demo.port'), 443);
  const bad = r.invalidValues().map((b) => `${b.layer}:${b.key}`);
  assert.deepEqual(bad.sort(), ['domain-policy:demo.port', 'local:demo.message', 'local:gone.key']);
});

test('validation and unknown keys', () => {
  const r = new Registry(keys);
  assert.equal(r.validate('demo.port', 8443), 8443);
  assert.throws(() => r.validate('demo.port', 70000), isCode('registry.invalid-value'));
  assert.throws(() => r.validate('demo.port', '8443'), isCode('registry.invalid-value'));
  assert.throws(() => r.get('nope'), isCode('registry.unknown-key'));
  assert.deepEqual(new Registry(keys, { local: { 'demo.port': 1 } }).diff(r), ['demo.port']);
});

test('template views only expose declared keys', () => {
  const r = new Registry(keys);
  const v = r.view(['demo.*'], 'demo.conf');
  assert.equal(v.get('demo.message'), 'hi');
  assert.equal(v.get('demo.port'), 80);
  assert.throws(() => v.get('other.flag'), /without declaring/);
  assert.equal(r.view(['other.flag'], 'x').get('other.flag'), false);
  assert.ok(readsKey(['demo.*'], 'demo.port'));
  assert.ok(!readsKey(['demo.*'], 'demonstration.x'));
  assert.ok(readsKey(['other.flag'], 'other.flag'));
});

test('headers for every comment style', () => {
  const h = headerText('dhcp', 'dhcp.kea');
  assert.match(h, /^Generated by OpenDC \(module dhcp, template dhcp\.kea\)\. DO NOT EDIT/);
  assert.equal(withHeader('hash', 'dhcp', 'dhcp.kea', 'a=1\n'), `# ${h}\na=1\n`);
  assert.equal(withHeader('semicolon', 'dhcp', 'dhcp.kea', 'x'), `; ${h}\nx`);
  assert.equal(withHeader('slash', 'dhcp', 'dhcp.kea', 'x'), `// ${h}\nx`);
  assert.equal(withHeader('xml', 'dhcp', 'dhcp.kea', '<a/>'), `<!-- ${h} -->\n<a/>`);
  assert.equal(
    withHeader('xml', 'dhcp', 'dhcp.kea', '<?xml version="1.0"?>\n<a/>'),
    `<?xml version="1.0"?>\n<!-- ${h} -->\n<a/>`,
  );
  assert.equal(
    withHeader('xml', 'dhcp', 'dhcp.kea', '<?xml version="1.0"?><a/>'),
    `<?xml version="1.0"?>\n<!-- ${h} -->\n<a/>`,
  );
  assert.equal(withHeader('none', 'dhcp', 'dhcp.kea', 'raw'), 'raw');
  const json = JSON.parse(withHeader('json-field', 'dhcp', 'dhcp.kea', '{"_generated":"old","Dhcp4":{}}')) as Record<
    string,
    unknown
  >;
  assert.deepEqual(Object.keys(json), ['_generated', 'Dhcp4']);
  assert.equal(json._generated, h);
  assert.deepEqual(JSON.parse(withHeader('json-field', 'm', 'f', '')), { _generated: headerText('m', 'f') });
  assert.throws(() => withHeader('json-field', 'm', 'f', '[1]'), TypeError);
});

/** In-memory agent: files by fileId, a lock, and a call log. */
function fakeAgent(opts: { failService?: string; failWrite?: string; lockHeldBy?: string } = {}) {
  const files = new Map<string, string>();
  const calls: string[] = [];
  let token: string | null = null;
  const agent: RegistryAgent = {
    read: async (fileId) => {
      const c = files.get(fileId);
      return { content: c ?? null, sha256: c === undefined ? null : sha(c) };
    },
    write: async (fileId, content, expected) => {
      calls.push(`write ${fileId}`);
      if (opts.failWrite === fileId)
        throw new PlatformError('agent.op-failed', { op: 'file.writeManaged', reason: 'disk full', requestId: 'x' });
      const cur = files.get(fileId);
      if ((cur === undefined ? null : sha(cur)) !== expected)
        throw new PlatformError('agent.stale-file', { fileId, expected: String(expected), actual: 'x' });
      files.set(fileId, content);
      return { changed: cur !== content, sha256: sha(content) };
    },
    restore: async (fileId) => {
      calls.push(`restore ${fileId}`);
    },
    service: async (action, unit) => {
      calls.push(`${action} ${unit}`);
      if (opts.failService === unit) throw new Error(`${unit} failed to ${action}`);
    },
    lock: async (holder) => {
      if (opts.lockHeldBy) return { acquired: false, heldBy: opts.lockHeldBy, since: '2026-10-24T00:00:00Z' };
      if (token) return { acquired: false, heldBy: 'someone', since: 'now' };
      token = 'a'.repeat(32);
      calls.push(`lock ${holder}`);
      return { acquired: true, token };
    },
    unlock: async () => {
      token = null;
      calls.push('unlock');
    },
  };
  return { agent, files, calls };
}

const tpl = (
  fileId: string,
  reads: string[],
  onChange: TemplateEntry['onChange'] = [],
  roles: TemplateEntry['roles'] = ['any'],
): TemplateEntry => ({
  module: 'demo',
  fileId,
  render: (v) =>
    reads
      .map((k) => `${k.replace('.*', '')} = ${JSON.stringify(v.get(k.endsWith('.*') ? 'demo.message' : k))}`)
      .join('\n') + '\n',
  reads,
  onChange,
  roles,
  comment: 'hash',
});

function service(agent: RegistryAgent, templates: TemplateEntry[], role: 'dc' | 'member' = 'dc'): RegistryService {
  return new RegistryService({
    agent,
    keys: new Registry(keys),
    templates,
    node: { hostname: 'dc1', fqdn: 'dc1.x', role },
    holder: 'test',
  });
}

test('set: validates, writes the layer, renders only affected templates, runs handlers once', async () => {
  const f = fakeAgent();
  const svc = service(f.agent, [
    tpl('demo.a', ['demo.*'], [{ kind: 'service', action: 'reload', unit: 'kea' }]),
    tpl('demo.b', ['demo.message'], [{ kind: 'service', action: 'try-reload-or-restart', unit: 'kea' }]),
    tpl('demo.c', ['other.flag'], [{ kind: 'service', action: 'restart', unit: 'x' }]),
  ]);
  const r = await svc.set('demo.message', 'hello');
  assert.deepEqual(r.rendered, ['demo.a', 'demo.b']);
  assert.deepEqual(r.changed, ['demo.a', 'demo.b']);
  assert.deepEqual(r.handlers, ['reload kea']);
  const layer = JSON.parse(f.files.get(LAYER_FILES.local) ?? '{}') as {
    _generated: string;
    values: Record<string, unknown>;
  };
  assert.ok(layer._generated.startsWith('Generated by OpenDC'));
  assert.deepEqual(layer.values, { 'demo.message': 'hello' });
  assert.ok(f.files.get('demo.a')?.startsWith('# Generated by OpenDC (module demo, template demo.a)'));
  assert.ok(f.files.get('demo.a')?.includes('demo = "hello"'));
  assert.ok(f.files.has(RENDERED_FILE));
  assert.deepEqual(
    f.calls.filter((c) => c.startsWith('lock') || c === 'unlock'),
    ['lock test', 'unlock'],
  );

  // setting the same value again changes nothing on disk
  f.calls.length = 0;
  const again = await svc.set('demo.message', 'hello');
  assert.deepEqual(again.changed, []);
  assert.deepEqual(again.handlers, []);

  // unset falls back to the default
  await svc.set('demo.message', undefined);
  assert.ok(f.files.get('demo.a')?.includes('demo = "hi"'));
  assert.deepEqual((JSON.parse(f.files.get(LAYER_FILES.local) ?? '{}') as { values: object }).values, {});
  // forced layer wins over local
  await svc.set('demo.message', 'loc');
  await svc.set('demo.message', 'forced', 'forced');
  assert.ok(f.files.get('demo.a')?.includes('demo = "forced"'));
  assert.equal((await svc.load()).explain('demo.message').layer, 'forced');
});

test('set rejects invalid values and unknown keys without writing', async () => {
  const f = fakeAgent();
  const svc = service(f.agent, [tpl('demo.a', ['demo.*'])]);
  await assert.rejects(svc.set('demo.port', 'eighty'), isCode('registry.invalid-value'));
  await assert.rejects(svc.set('nope.key', 1), isCode('registry.unknown-key'));
  await assert.rejects(svc.set('nope.key', undefined), isCode('registry.unknown-key'));
  assert.deepEqual(
    f.calls.filter((c) => c.startsWith('write')),
    [],
  );
  assert.ok(f.calls.includes('unlock'));
});

test('commit renders by role; a busy lock fails fast', async () => {
  const f = fakeAgent();
  const svc = service(f.agent, [
    tpl('demo.dc', ['demo.*'], [], ['writable-dc']),
    tpl('demo.member', ['demo.*'], [], ['member']),
  ]);
  assert.deepEqual((await svc.commit()).rendered, ['demo.dc']);
  assert.deepEqual(
    (await service(f.agent, [tpl('demo.member', ['demo.*'], [], ['member'])], 'member').commit()).rendered,
    ['demo.member'],
  );
  await assert.rejects(
    service(fakeAgent({ lockHeldBy: 'watcher' }).agent, []).commit(),
    (e: unknown) => isCode('registry.locked')(e) && (e as PlatformError).message.includes('watcher'),
  );
});

test('a failing handler rolls back every written file', async () => {
  const f = fakeAgent({ failService: 'kea' });
  const svc = service(f.agent, [
    tpl('demo.a', ['demo.*'], [{ kind: 'service', action: 'reload', unit: 'kea' }]),
    tpl('demo.b', ['demo.*']),
  ]);
  await assert.rejects(
    svc.commit(),
    (e: unknown) => isCode('registry.commit-failed')(e) && (e as PlatformError).message.includes('reload kea'),
  );
  assert.deepEqual(
    f.calls.filter((c) => c.startsWith('restore')),
    ['restore demo.b', 'restore demo.a'],
  );
  assert.ok(f.calls.includes('unlock'));
});

test('a failing render or write writes nothing / rolls back', async () => {
  const f = fakeAgent();
  const broken: TemplateEntry = { ...tpl('demo.x', ['demo.*']), render: (v) => String(v.get('other.flag')) };
  await assert.rejects(
    service(f.agent, [tpl('demo.a', ['demo.*']), broken]).commit(),
    (e: unknown) => isCode('registry.commit-failed')(e) && (e as PlatformError).message.includes('render demo.x'),
  );
  assert.deepEqual(
    f.calls.filter((c) => c.startsWith('write')),
    [],
  );

  const w = fakeAgent({ failWrite: 'demo.b' });
  await assert.rejects(
    service(w.agent, [tpl('demo.a', ['demo.*']), tpl('demo.b', ['demo.*'])]).commit(),
    isCode('registry.commit-failed'),
  );
  assert.deepEqual(
    w.calls.filter((c) => c.startsWith('restore')),
    ['restore demo.a'],
  );
});

test('drift detection flags manual edits and missing files', async () => {
  const f = fakeAgent();
  const svc = service(f.agent, [tpl('demo.a', ['demo.*']), tpl('demo.b', ['demo.message'])]);
  assert.deepEqual(await svc.drift(), [
    { fileId: 'demo.a', state: 'never-rendered' },
    { fileId: 'demo.b', state: 'never-rendered' },
  ]);
  await svc.commit();
  assert.deepEqual(await svc.drift(), []);
  f.files.set('demo.a', (f.files.get('demo.a') ?? '') + 'manual edit\n');
  f.files.delete('demo.b');
  assert.deepEqual(await svc.drift(), [
    { fileId: 'demo.a', state: 'modified' },
    { fileId: 'demo.b', state: 'missing' },
  ]);
  // a corrupt rendered record is treated as "never rendered", not as a crash
  f.files.set(RENDERED_FILE, 'not json');
  assert.equal((await svc.drift())[0]?.state, 'never-rendered');
});

test('a corrupt layer file is reported, not silently ignored', async () => {
  const f = fakeAgent();
  f.files.set(LAYER_FILES.local, '{"schemaVersion": 1, "values": [1]}');
  await assert.rejects(service(f.agent, []).load(), isCode('registry.layer-corrupt'));
  f.files.set(LAYER_FILES.local, '   ');
  assert.equal((await service(f.agent, []).load()).get('demo.port'), 80);
});

test('the domain-policy layer: written by setPolicyLayer, below local, re-renders only what changed', async () => {
  const f = fakeAgent();
  const svc = service(f.agent, [tpl('demo.a', ['demo.message']), tpl('demo.c', ['other.flag'])]);
  await svc.commit();
  const r = await svc.setPolicyLayer({ 'demo.message': 'policy', 'demo.port': 1 });
  assert.deepEqual(r?.changed, ['demo.a']);
  assert.ok(f.files.get('demo.a')?.includes('demo.message = "policy"'));
  assert.equal((await svc.load()).explain('demo.message').layer, 'domain-policy');
  // demo.port is not policy-settable: stored, but ignored by the registry
  assert.equal((await svc.load()).explain('demo.port').layer, 'default');
  assert.deepEqual((JSON.parse(f.files.get(POLICY_FILE) ?? '{}') as { values: object }).values, {
    'demo.message': 'policy',
    'demo.port': 1,
  });
  // unchanged values: nothing written
  f.calls.length = 0;
  assert.equal(await svc.setPolicyLayer({ 'demo.port': 1, 'demo.message': 'policy' }), null);
  assert.deepEqual(
    f.calls.filter((c) => c.startsWith('write')),
    [],
  );
  // a local value wins over the policy
  await svc.set('demo.message', 'local');
  assert.ok(f.files.get('demo.a')?.includes('demo.message = "local"'));
  // the policy goes away: back to the default for other.flag (never set), local stays
  const gone = await svc.setPolicyLayer({});
  assert.deepEqual(gone?.changed, []);
});
