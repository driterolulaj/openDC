/**
 * Acceptance 5 end to end, minus the real filesystem: CLI -> registry -> agent socket (generated allowlist)
 * -> OS layer. `opendc registry set` renders the core demo file with its header; a manual edit shows up in
 * `opendc registry drift`; `commit` repairs it.
 */
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { AgentClient } from '@opendc/shared/agent';
import { AgentServer, NodeStateFile, SecretFiles, SetupToken, loadAllowlist } from '@opendc/agent';
import type { OsActions, OsFacts } from '@opendc/os';
import { agentPort } from '@opendc/registry';
import { registryKeys, templates } from '@opendc/modules/generated/registry';
import { initI18n } from './i18n.ts';
import { run } from './run.ts';
import { moduleResources } from './resources.ts';

const sha = (s: string): string => createHash('sha256').update(s).digest('hex');

function memoryOs(): { os: OsActions; files: Map<string, string> } {
  const files = new Map<string, string>();
  const facts = {
    adapter: 'debian',
    release: { id: 'debian', idLike: [], versionId: '13', prettyName: 'Debian GNU/Linux 13 (trixie)', arch: 'x86_64' },
    paths: {
      managedFile: (k: string) => `/mem/${k}`,
      managedRoots: () => ['/mem'],
      etc: '/etc/opendc',
      secrets: '',
      lib: '',
      state: '',
      run: '',
    },
    samba: { version: async () => null },
  } as unknown as OsFacts;
  const os = {
    facts,
    services: { status: async () => ({ active: 'active', sub: 'running', enabled: true }) },
    files: {
      writeManaged: async (p: string, c: string) => {
        const prev = files.get(p);
        files.set(p, c);
        return { changed: prev !== c, sha256: sha(c), previousSha256: prev === undefined ? null : sha(prev) };
      },
      readManaged: async (p: string) =>
        files.has(p) ? { content: files.get(p) ?? '', sha256: sha(files.get(p) ?? '') } : null,
      restorePrevious: async () => ({ restored: false, sha256: null }),
    },
    system: {
      info: async () => ({
        hostname: 'sdc1',
        fqdn: 'sdc1.small.opendc.test',
        kernel: '6.12',
        uptimeSec: 5,
        memTotal: 4e9,
        cpus: 2,
      }),
    },
  } as unknown as OsActions;
  return { os, files };
}

test('opendc registry set/drift/commit through the agent socket', async () => {
  const mem = memoryOs();
  const stateDir = mkdtempSync(join(tmpdir(), 'opendc-cli-state-'));
  const server = new AgentServer({
    os: mem.os,
    allowlist: loadAllowlist(),
    role: 'primary-dc',
    confirmKey: null,
    log: () => undefined,
    node: new NodeStateFile(stateDir),
    secrets: new SecretFiles(stateDir),
    token: new SetupToken(stateDir),
  }).createServer('cli');
  const path =
    process.platform === 'win32'
      ? `\\\\.\\pipe\\opendc-cli-test-${String(process.pid)}`
      : join(tmpdir(), `opendc-cli-${String(process.pid)}.sock`);
  await new Promise<void>((r) => server.listen(path, r));
  try {
    const client = new AgentClient(path, 'cli');
    const out: string[] = [];
    const err: string[] = [];
    const deps = {
      t: await initI18n(await moduleResources(), 'en'),
      client,
      agent: agentPort(client, { name: 'tester', via: 'cli' }),
      keys: registryKeys,
      templates,
      out: (s: string) => out.push(s),
      err: (s: string) => err.push(s),
      user: 'tester',
      io: {
        readSecret: async () => null,
        readPassword: async () => '',
        ask: async () => null,
      },
    };
    const demo = '/mem/opendc.demo';

    assert.equal(await run(['registry', 'set', 'core.demo.message', 'Hello lab'], deps), 0, err.join('\n'));
    const content = mem.files.get(demo) ?? '';
    assert.match(content, /^# Generated by OpenDC \(module core, template core\.demo\)\. DO NOT EDIT/);
    assert.match(content, /message = Hello lab\nnode = sdc1\.small\.opendc\.test\nrole = primary-dc\n$/);
    assert.match(mem.files.get('/mem/opendc.registry.local') ?? '', /"core\.demo\.message": "Hello lab"/);

    out.length = 0;
    assert.equal(await run(['registry', 'get', 'core.demo.message', '--explain'], deps), 0);
    assert.match(out.join('\n'), /core\.demo\.message = Hello lab {2}\(from local\)/);

    out.length = 0;
    assert.equal(await run(['registry', 'drift'], deps), 0);
    assert.match(out.join('\n'), /No drift/);

    mem.files.set(demo, content + 'tampered = yes\n');
    out.length = 0;
    assert.equal(await run(['registry', 'drift'], deps), 1);
    assert.match(out.join('\n'), /core\.demo: modified by hand/);

    assert.equal(await run(['registry', 'commit'], deps), 0);
    assert.equal(mem.files.get(demo), content);
    assert.equal(await run(['registry', 'drift'], deps), 0);

    // values are typed: a number for a port, JSON for lists, and a clear error for nonsense
    assert.equal(await run(['registry', 'set', 'core.api.listenPort', '9443'], deps), 0, err.join('\n'));
    assert.match(mem.files.get('/mem/opendc.registry.local') ?? '', /"core\.api\.listenPort": 9443/);
    err.length = 0;
    assert.equal(await run(['registry', 'set', 'core.api.listenPort', 'eighty'], deps), 1);
    assert.match(err.join('\n'), /^Error: Value for core\.api\.listenPort is invalid/);
    assert.match(err.join('\n'), /Fix: See opendc registry describe core\.api\.listenPort/);

    out.length = 0;
    assert.equal(await run(['registry', 'describe', 'core.api.listenPort'], deps), 0);
    assert.match(out.join('\n'), /TCP port the console\/API listens on\./);

    // German output follows the locale
    const de = { ...deps, t: await initI18n(await moduleResources(), 'de') };
    err.length = 0;
    assert.equal(await run(['registry', 'get', 'core.nope'], de), 1);
    assert.match(err.join('\n'), /^Fehler: Registry-Schlüssel core\.nope existiert nicht\./);

    out.length = 0;
    assert.equal(await run(['agent', 'info', '--json'], deps), 0);
    assert.equal((JSON.parse(out.join('')) as { role: string }).role, 'primary-dc');
    assert.equal(await run(['bogus'], deps), 2);
    assert.equal(await run([], deps), 2);
    assert.equal(await run(['--help'], deps), 0);
  } finally {
    await new Promise<void>((r) => server.close(() => r()));
  }
});
